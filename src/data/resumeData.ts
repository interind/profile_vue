export interface ContactItem {
  /** text-метка бейджа (например "+7 969 022 92 80") */
  label: string;
  /** подпись/тип контакта (Телефон, Email, GitHub …) */
  caption: string;
  /** ссылка (tel:, mailto:, https) */
  href: string;
  /** какой inline-SVG показать */
  type: 'phone' | 'email' | 'github' | 'linkedin' | 'telegram' | 'location';
}

export interface ExperienceItem {
  company: string;
  role: string;
  period: string;
  /** короткий стек позиции — рендерится тегами TechTag */
  stack: string[];
  /** достижения: формат «сделал X → получил Y». Верните свои формулировки сюда. */
  achievements: string[];
}

export interface SkillGroup {
  title: string;
  items: string[];
}

export interface ProjectHighlightData {
  title: string;
  subtitle: string;
  /** бизнес-суть проекта (короткие пункты) */
  summary: string[];
  /** результаты — «прозрачность изменений», «контроль прав» и т.д. */
  results: string[];
  stack: string[];
}

export interface ResumeDataModel {
  name: string;
  headline: string;
  /** чем занимаюсь — короткий тезис для HR */
  focus: string;
  location: string;
  /** 3–4 буллета «о себе»: только конкретика */
  about: string[];
  contacts: ContactItem[];
  experience: ExperienceItem[];
  skills: SkillGroup[];
  project: ProjectHighlightData;
}

